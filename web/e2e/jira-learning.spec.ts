test("register one reviewed commit and its deployment through the shared handoff", async ({ page }) => {
  test.setTimeout(60000);
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.request.post(`${base}/api/login`, { data: { username: "rm", password: "rm" } });
  const response = await page.request.post(`${base}/api/jira-agent/learning/jobs`, { data: { issue_keys: ["MC3-1"], agent_group: "HPC", title: "统一登记验证" } });
  expect(response.ok()).toBeTruthy();
  const { job } = await response.json();
  const detail = async () => (await page.request.get(`${base}/api/jira-agent/learning/jobs/${job.id}`)).json();
  await expect.poll(async () => (await detail()).job.status).toBe("completed");
  const proposal = (await detail()).proposals[0];
  expect((await page.request.post(`${base}/api/jira-agent/learning/proposals/${proposal.id}/review`, { data: { decision: "approved" } })).ok()).toBeTruthy();
  const committed = await page.request.post(`${base}/api/_testing/learning-commit?job_id=${job.id}`);
  expect(committed.ok()).toBeTruthy();
  const { commit_sha } = await committed.json();
  await page.goto(`${base}/jira-agent?view=learning&learning_list=jobs&learning_job=${job.id}`);
  await page.locator("summary").filter({ hasText: "人工更新与验证" }).click();
  await page.getByRole("tab", { name: "登记提交", exact: true }).click();
  await page.getByRole("checkbox", { name: /明确可比条件与结论边界/ }).check();
  await page.getByLabel("统一入库提交 SHA").fill(commit_sha);
  await page.getByRole("button", { name: "核对并登记", exact: true }).click();
  await expect(page.locator(".jira-learning-handoff").getByRole("status")).toHaveText("已核对提交并登记入库。");
  expect((await detail()).proposals[0].published_commit).toBe(commit_sha);
  await page.getByRole("tab", { name: "登记部署", exact: true }).click();
  await expect(page.getByLabel("部署提交")).toHaveValue(commit_sha);
  await page.getByLabel("部署目标服务").fill("isolated-analysis");
  await page.getByLabel("交付备注").fill("隔离环境人工核对");
  await page.getByRole("button", { name: "登记部署结果", exact: true }).click();
  await expect(page.locator(".jira-learning-handoff").getByRole("status")).toContainText("已登记部署");
  await expect(page.locator(".jira-learning-handoff")).toContainText("isolated-analysis · 部署成功 · 人工登记");
  const records = (await detail()).proposals[0].deployments;
  expect(records).toHaveLength(1);
  expect(records[0]).toMatchObject({ commit_sha, target: "isolated-analysis", result: "succeeded" });
  await page.reload();
  await page.locator("summary").filter({ hasText: "人工更新与验证" }).click();
  await page.getByRole("tab", { name: "登记部署", exact: true }).click();
  await expect(page.locator(".jira-learning-handoff")).toContainText("隔离环境人工核对");
  await page.screenshot({ path: "/tmp/jira-learning-shared-deployment.png", fullPage: true });
  expect(errors).toEqual([]);
});
