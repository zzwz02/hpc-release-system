/** Uses the isolated website and learning protocol peer, no Jira/model/GPU writes. */
import { test, expect } from "@playwright/test";
const base = process.env.JIRA_LEARNING_E2E_URL ?? "";
test.skip(!/^http:\/\/127\.0\.0\.1:\d+$/.test(base), "Requires isolated joint-learning fixture");

test("joint learning stays in one task through review, bundle export and revision", async ({ page }) => {
  test.setTimeout(60000);
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  expect((await page.request.post(`${base}/api/login`, { data: { username: "rm", password: "rm" } })).ok()).toBeTruthy();
  await page.goto(`${base}/jira-agent?view=learning`);
  await page.getByRole("checkbox", { name: "选择 Jira MC3-1", exact: true }).check();
  await page.getByRole("checkbox", { name: "选择 Jira MC3-2", exact: true }).check();
  await page.getByRole("button", { name: "联合学习（2 张）" }).click();
  await page.getByLabel("学习任务名称").fill("版本定位方法联合学习");
  await page.getByRole("button", { name: "开始学习", exact: true }).click();
  await expect(page.getByRole("heading", { name: "版本定位方法联合学习" })).toBeVisible();
  await expect(page.getByRole("tab", { name: "学习任务", exact: true })).toHaveAttribute("aria-selected", "true");
  const proposal = page.locator(".jira-learning-proposal-toggle").filter({ hasText: "明确可比条件与结论边界" });
  await expect(proposal).toBeVisible({ timeout: 20000 });
  await expect(proposal).toHaveText(/2 张 Jira/);
  const id = new URL(page.url()).searchParams.get("learning_job")!;
  const detail = await (await page.request.get(`${base}/api/jira-agent/learning/jobs/${id}`)).json();
  expect(detail.job.issue_keys).toEqual(["MC3-1", "MC3-2"]);
  expect(detail.turns).toHaveLength(1);
  await expect(page.getByRole("dialog", { name: "学习材料", exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "查看学习材料", exact: true })).toHaveCount(0);
  const conversation = page.getByTestId("jira-learning-timeline");
  if (!(await conversation.isVisible())) await page.locator("summary").filter({ hasText: /^学习对话/ }).click();
  await expect(conversation.getByText("读取材料", { exact: true })).toHaveCount(2);
  const material = conversation.locator(".learning-material-list details").first();
  await expect(material).not.toHaveAttribute("open", "");
  await material.locator("summary").click();
  await expect(material.getByText("运行时版本差异的定位，保留可核对的现象和条件。", { exact: true })).toBeVisible();
  await material.locator("summary").click();
  await page.screenshot({ path: "/tmp/jira-joint-learning-overview.png", fullPage: true });
  await proposal.click();
  await page.locator("summary").filter({ hasText: "修改对比" }).click();
  await expect(page.getByText("对照条件需能支持结论，未验证的场景应说明限制。", { exact: false }).first()).toBeVisible();
  const evidence = page.locator("details").filter({ has: page.locator(":scope > summary").filter({ hasText: "来源证据" }) }).first();
  await expect(evidence).not.toHaveAttribute("open", "");
  await page.locator("summary").filter({ hasText: "来源证据" }).click();
  await expect(page.locator("summary").filter({ hasText: "MC3-1" }).first()).toBeVisible();
  await expect(page.locator("summary").filter({ hasText: "MC3-2" }).first()).toBeVisible();
  await page.screenshot({ path: "/tmp/jira-joint-learning-review.png", fullPage: true });
  await page.getByRole("button", { name: "审核通过", exact: true }).click();
  await page.locator("summary").filter({ hasText: "人工更新与验证" }).click();
  await page.getByRole("checkbox", { name: /明确可比条件与结论边界/ }).check();
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "下载补丁包" }).click();
  expect((await download).suggestedFilename()).toBe("skill-proposals.zip");
  await page.getByRole("tab", { name: "关联验证", exact: true }).click();
  await expect(page.getByLabel("关联测试记录")).toBeVisible();
  await page.getByLabel("补充学习要求").fill("请保留对未覆盖场景的说明。");
  await page.getByRole("button", { name: "发送", exact: true }).click();
  await expect(page.locator(".jira-learning-proposal-toggle").filter({ hasText: "明确可比条件与结论边界" })).toContainText("第 2 版", { timeout: 20000 });
  await expect(page.locator(".jira-learning-proposal-toggle").filter({ hasText: "明确可比条件与结论边界" })).toContainText("待审核");
  await expect(page.locator(".jira-learning-proposal-toggle").filter({ hasText: "明确可比条件与结论边界" })).toHaveCount(1);
  await page.reload();
  await expect(page.getByRole("heading", { name: "版本定位方法联合学习" })).toBeVisible();
  expect(errors).toEqual([]);
});

test("compare related proposals and consolidate without changing originals", async ({ page }) => {
  test.setTimeout(60000);
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.request.post(`${base}/api/login`, { data: { username: "rm", password: "rm" } });
  async function create(key: string) {
    const response = await page.request.post(`${base}/api/jira-agent/learning/jobs`, { data: { issue_keys: [key], agent_group: "HPC", title: `关联比较 ${key}` } });
    expect(response.ok()).toBeTruthy();
    const job = (await response.json()).job;
    await expect.poll(async () => (await (await page.request.get(`${base}/api/jira-agent/learning/jobs/${job.id}`)).json()).job.status).toBe("completed");
    return (await (await page.request.get(`${base}/api/jira-agent/learning/jobs/${job.id}`)).json()).proposals[0];
  }
  const first = await create("MC3-1");
  const second = await create("MC3-2");
  await page.goto(`${base}/jira-agent?view=learning&learning_list=jobs&learning_job=${first.job_id}`);
  await page.locator(".jira-learning-proposal-toggle").filter({ hasText: "明确可比条件与结论边界" }).click();
  await page.locator("summary").filter({ hasText: "相关提案" }).click();
  const row = page.getByTestId(`learning-related-${second.id}`);
  await row.getByRole("button", { name: "比较修改", exact: true }).click();
  const comparison = page.getByRole("region", { name: "提案比较" });
  await expect(comparison.getByText("共同文件的修改内容相同", { exact: true })).toBeVisible();
  await expect(comparison.locator("pre")).toHaveCount(2);
  await page.screenshot({ path: "/tmp/jira-learning-proposal-comparison.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(comparison).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await row.getByRole("checkbox").check();
  await page.getByLabel("整理意见（可选）").fill("保留有效条件，合并重复说明。");
  await page.getByRole("button", { name: "一起整理", exact: true }).click();
  await expect(page.getByRole("heading", { name: /提案整理/ })).toBeVisible();
  const combined = new URL(page.url()).searchParams.get("learning_job");
  expect(combined).not.toBe(first.job_id);
  const proposal = page.locator(".jira-learning-proposal-toggle").filter({ hasText: "明确可比条件与结论边界" });
  await expect(proposal).toContainText("待审核", { timeout: 20000 });
  for (const original of [first, second]) {
    const detail = await (await page.request.get(`${base}/api/jira-agent/learning/jobs/${original.job_id}`)).json();
    expect(detail.proposals[0].status).toBe("pending");
  }
  await page.locator("summary").filter({ hasText: "本次整理的原提案" }).click();
  await expect(page.getByRole("button", { name: "关闭重复项" }).first()).toBeDisabled();
  await proposal.click();
  await page.getByRole("button", { name: "审核通过", exact: true }).click();
  await expect(page.getByRole("button", { name: "关闭重复项" }).first()).toBeEnabled();
  await page.getByRole("button", { name: "关闭重复项" }).first().click();
  await expect(page.locator(".learning-origins").getByText("已关闭", { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});

