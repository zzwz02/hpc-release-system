import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { parseCsvRows } from "../src/lib/csv";

const base = process.env.QA_REPORT_FILTERS_E2E_URL ?? "";
test.skip(!/^http:\/\/127\.0\.0\.1:\d+$/.test(base), "Requires isolated tests.run_app_info_site --lookup --qa-report-pagination and Vite");

test("shows every result without pagination and exports filtered results in server sort order", async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  expect((await page.request.post(base + "/api/login", { data: { username: "app_qa", password: "test-password" } })).ok()).toBeTruthy();
  await page.goto(base + "/qa?tab=report");
  const pane = page.getByTestId("qa-results-pane");
  const table = pane.getByRole("table", { name: "QA 测试结果", exact: true });
  await expect(table.locator("tbody tr")).toHaveCount(65);
  await expect(pane.getByText("65 行", { exact: true })).toBeVisible();
  await expect(table.getByText("pagination64", { exact: true })).toBeVisible();
  await expect(pane.getByRole("button", { name: "下一页", exact: true })).toHaveCount(0);
  await expect(pane.getByRole("heading", { name: "QA 测试结果", exact: true })).toHaveCount(0);
  await page.screenshot({ path: "/tmp/qa-log-all-results-desktop.png" });
  const filter = pane.getByLabel("qa_status 列筛选");
  await filter.fill("fail");
  await expect(table.locator("tbody tr")).toHaveCount(5);
  await expect(table.getByText("pagination64", { exact: true })).toBeVisible();
  await expect(filter).toBeFocused();
  await expect(pane.getByText("5 行", { exact: true })).toBeVisible();
  await filter.fill("");
  await expect(table.locator("tbody tr")).toHaveCount(65);
  await pane.getByLabel("test_name 列筛选").fill("pagination64");
  await expect(table.locator("tbody tr")).toHaveCount(1);
  await expect(pane.getByText("1 行", { exact: true })).toBeVisible();
  await pane.getByLabel("test_name 列筛选").fill("");
  await pane.getByLabel("查询 QA 结果").fill("run-pagination-64");
  await pane.getByRole("button", { name: "查询结果", exact: true }).click();
  await expect(table.getByText("pagination64", { exact: true })).toBeVisible();
  await expect(table.locator("tbody tr")).toHaveCount(1);
  await pane.getByLabel("查询 QA 结果").fill("");
  await pane.getByRole("button", { name: "查询结果", exact: true }).click();
  await expect(table.locator("tbody tr")).toHaveCount(65);
  const header = table.getByRole("columnheader", { name: "test_name", exact: true });
  await header.click();
  await expect(header).toHaveAttribute("aria-sort", "ascending");
  await expect(pane.getByRole("button", { name: "导出 CSV", exact: true })).toBeEnabled();
  await header.click();
  await expect(header).toHaveAttribute("aria-sort", "descending");
  await expect(table.locator("tbody tr").first()).toContainText("pagination64");
  const downloaded = page.waitForEvent("download");
  await pane.getByRole("button", { name: "导出 CSV", exact: true }).click();
  const rows = parseCsvRows(await readFile((await (await downloaded).path())!, "utf8"));
  expect(rows).toHaveLength(66);
  const nameIndex = rows[0].indexOf("test_name");
  expect(rows[1][nameIndex]).toBe("pagination64");
  expect(rows[65][nameIndex]).toBe("pagination0");
  await page.setViewportSize({ width: 390, height: 1000 });
  await page.evaluate(() => window.scrollTo(0, 0));
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: "/tmp/qa-log-all-results-mobile.png" });
});
